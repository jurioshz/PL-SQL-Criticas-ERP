SELECT DISTINCT A.NROPEDVENDA, A.NROEMPRESA,
       'CGO 102 Nao Perm p/ CD 501/603' MENSAGEM
FROM CONSINCO.MAD_PEDVENDA A
WHERE A.SITUACAOPED != 'C'
AND A.CODGERALOPER = 102
AND A.NROEMPRESA IN (8,42,46,47,48,49,50,51,54,55)
AND A.SEQPESSOA IN (501,603)
AND A.DTAINCLUSAO >= SYSDATE - 70
