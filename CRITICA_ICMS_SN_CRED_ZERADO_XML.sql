-- Ticket 799768
-- Fornecedor SN com % ou valor de crédito ICMS SN zerado no XML
SELECT 
DISTINCT X.SEQAUXNOTAFISCAL AS SEQAUXNOTAFISCAL, X.NUMERONF, X.NROEMPRESA, Y.SEQAUXNFITEM, 'B' AS BLOQAUTOR, 126 AS CODINCONSISTENC,
'Prod. ' || Y.SEQPRODUTO || ': Fornecedor Simples Nacional com % / valor de crédito de ICMS SN zerado no XML - Trocar a nota fiscal com o fornecedor.' AS MENSAGEM
FROM CONSINCO.MLF_AUXNOTAFISCAL X
INNER JOIN CONSINCO.MLF_AUXNFITEM Y ON Y.SEQAUXNOTAFISCAL = X.SEQAUXNOTAFISCAL
INNER JOIN CONSINCO.TMP_M000_NF Z ON Z.M000_NR_CHAVE_ACESSO = X.NFECHAVEACESSO
INNER JOIN CONSINCO.TMP_M014_ITEM XI ON XI.M000_ID_NF = Z.M000_ID_NF AND XI.M014_NR_ITEM = Y.SEQITEMNFXML
INNER JOIN CONSINCO.MAF_FORNECEDOR XII ON XII.SEQFORNECEDOR = X.SEQPESSOA
INNER JOIN CONSINCO.MAX_CODGERALOPER XIII ON XIII.CODGERALOPER = X.CODGERALOPER
WHERE XII.MICROEMPRESA = 'S'
AND XIII.TIPCGO = 'E'
AND NVL(XI.M014_CD_CFOP,0) IN (5101, 5102, 6101, 6102)
AND (NVL(XI.M014_VL_PERC_CRED_SN,0) = 0 OR NVL(XI.M014_VL_CRED_ICMS_SN,0) = 0)
