-- Ticket 799768
-- Fornecedor SN com valor de crédito ICMS SN do XML divergente do C5
SELECT DISTINCT X.SEQAUXNOTAFISCAL AS SEQAUXNOTAFISCAL, X.NUMERONF, X.NROEMPRESA, Y.SEQAUXNFITEM, 'B' AS BLOQAUTOR, 127 AS CODINCONSISTENC,
'Prod. ' || Y.SEQPRODUTO || ': Crédito ICMS SN divergente - XML ' || TO_CHAR(XI.M014_VL_PERC_CRED_SN,'FM990D00','NLS_NUMERIC_CHARACTERS='',.''') || '% / ' || TO_CHAR(XI.M014_VL_CRED_ICMS_SN,'FM999G999G990D00','NLS_NUMERIC_CHARACTERS='',.''') || ' x C5 ' || TO_CHAR(NVL(Y.VLRICMSSIMPLES,0),'FM999G999G990D00','NLS_NUMERIC_CHARACTERS='',.''') || ' - Abrir chamado para o Cadastro Tributário realizar a análise.' AS MENSAGEM
FROM CONSINCO.MLF_AUXNOTAFISCAL X
INNER JOIN CONSINCO.MLF_AUXNFITEM Y ON Y.SEQAUXNOTAFISCAL = X.SEQAUXNOTAFISCAL
INNER JOIN CONSINCO.TMP_M000_NF Z ON Z.M000_NR_CHAVE_ACESSO = X.NFECHAVEACESSO
INNER JOIN CONSINCO.TMP_M014_ITEM XI ON XI.M000_ID_NF = Z.M000_ID_NF AND XI.M014_NR_ITEM = Y.SEQITEMNFXML
INNER JOIN CONSINCO.MAF_FORNECEDOR XII ON XII.SEQFORNECEDOR = X.SEQPESSOA
INNER JOIN CONSINCO.MAX_CODGERALOPER XIII ON XIII.CODGERALOPER = X.CODGERALOPER
WHERE XII.MICROEMPRESA = 'S'
AND XIII.TIPCGO = 'E'
AND NVL(XI.M014_VL_PERC_CRED_SN,0) > 0
AND NVL(XI.M014_VL_CRED_ICMS_SN,0) > 0
AND ABS(XI.M014_VL_CRED_ICMS_SN - NVL(Y.VLRICMSSIMPLES,0)) > 0.05
